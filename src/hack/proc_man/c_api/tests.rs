#![cfg(test)]

use {
    std::{
        os::{
            linux::net::SocketAddrExt,
            unix::net::{SocketAddr, UnixDatagram},
        },
        thread,
    },
    crate::hack::Result,
};

const FIRST: &[u8] = &[0, 1, 2];
const SECOND: &[u8] = &[9, 9, 9, 9, 9];

#[test]
fn std() -> Result<()> {
    let server_address = SocketAddr::from_abstract_name(&[
        0x63, 0x35, 0xe9, 0x4b, 0x1d, 0x47, 0xd5, 0x0a,     0xe8, 0xe1, 0xcf, 0x9b, 0x60, 0x1c, 0x84, 0x88,
        0xf3, 0x50, 0x0d, 0x24, 0xc9, 0x23, 0xdd, 0x57,     0x5b, 0x67, 0xf3, 0x2f, 0xc5, 0x53, 0x1a, 0x11,
        0x9c, 0x53, 0x6a, 0xa5, 0x47, 0xd0, 0x54, 0xe7,     0xed, 0x5a, 0x0b, 0xa2, 0xc9, 0xd0, 0x25, 0x14,
        0x15, 0xe2, 0xf9, 0xb6, 0xec, 0xdc, 0x3b, 0x51,     0x7b, 0xcb, 0x93, 0x99, 0xea, 0x98, 0xd2, 0xeb,
    ])?;
    let server = UnixDatagram::bind_addr(&server_address)?;
    let server_thread = thread::spawn(move || {
        let mut buf = [u8::MIN; 10];
        let (size, address) = server.recv_from(&mut buf)?;
        assert_eq!(size, FIRST.len());
        assert_eq!(&buf[..FIRST.len()], FIRST);
        assert_eq!(server.send_to_addr(SECOND, &address)?, SECOND.len());
        Result::Ok(())
    });

    let client = UnixDatagram::bind_addr(&SocketAddr::from_abstract_name(&[
        0x2c, 0x0c, 0x60, 0xca, 0x89, 0x14, 0x2f, 0x0c,     0xbf, 0x12, 0x15, 0x55, 0x37, 0x36, 0xd8, 0xf3,
        0xcb, 0xfb, 0x06, 0xdf, 0xd6, 0x64, 0x6b, 0x29,     0x33, 0x47, 0xcb, 0x44, 0xf2, 0x60, 0x08, 0xab,
        0x36, 0xd1, 0x3d, 0x44, 0xb9, 0x5f, 0xc7, 0xac,     0x4d, 0xd5, 0x85, 0x6e, 0x96, 0x1e, 0x4d, 0xec,
        0x50, 0xb6, 0xb1, 0xaf, 0x79, 0x8f, 0x6b, 0x40,     0x3c, 0x38, 0xdc, 0x96, 0xf3, 0xb6, 0x3c, 0x2d,
    ])?)?;
    assert_ne!(server_address.as_abstract_name().unwrap(), client.local_addr()?.as_abstract_name().unwrap());
    assert_eq!(client.send_to_addr(FIRST, &server_address)?, FIRST.len());

    let mut buf = [u8::MIN; 10];
    let (size, address) = client.recv_from(&mut buf)?;
    assert_eq!(size, SECOND.len());
    assert_eq!(address.as_abstract_name().unwrap(), server_address.as_abstract_name().unwrap());
    assert_eq!(&buf[..SECOND.len()], SECOND);

    server_thread.join().unwrap()
}
